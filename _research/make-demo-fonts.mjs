// Download free substitute faces and alias them to the ORIGINAL family names,
// so every element that asks for "Tr 3 A" / "Ppneuemontreal Book" gets a real
// typeface instead of silently falling back to Arial.
import fs from 'node:fs';
import path from 'node:path';

const OUT = path.resolve('public/assets/demo/fonts');
fs.mkdirSync(OUT, { recursive: true });

const css = fs.readFileSync('_demo/google.css', 'utf8');

// Each @font-face block ends with a `unicode-range`; the latin block is the one
// whose range starts at U+0000. Grab that block per family+weight.
const blocks = [...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([\s\S]*?)\}/g)].map((m) => ({
  subset: m[1],
  body: m[2],
}));

const pick = (family, weight) => {
  const b = blocks.find(
    (x) =>
      x.subset === 'latin' &&
      new RegExp(`font-family:\\s*'${family}'`).test(x.body) &&
      new RegExp(`font-weight:\\s*${weight}\\b`).test(x.body)
  );
  return b && (b.body.match(/url\((https:\/\/[^)]+\.woff2)\)/) || [])[1];
};

const WANT = [
  // display face -> stands in for "Tr 3 A"
  { family: 'Archivo', weight: 400, alias: 'Tr 3 A', file: 'display-400.woff2' },
  { family: 'Archivo', weight: 500, alias: 'Tr 3 A', file: 'display-500.woff2' },
  { family: 'Archivo', weight: 700, alias: 'Tr 3 A', file: 'display-700.woff2' },
  // body face -> stands in for the PP Neue Montreal family
  { family: 'Manrope', weight: 400, alias: 'Ppneuemontreal Book', file: 'body-400.woff2' },
  { family: 'Manrope', weight: 500, alias: 'Ppneuemontreal', file: 'body-500.woff2' },
  { family: 'Manrope', weight: 700, alias: 'Ppneuemontreal', file: 'body-700.woff2' },
];

let rules = `/* Demo-build type substitution — generated by _research/make-demo-fonts.mjs.
   The original's commercial faces (Tr 3 A, PP Neue Montreal) are not licensed for
   redistribution, so the demo aliases those family names to free equivalents
   (Archivo, Manrope). Metrics differ, so line breaks will not match the original;
   the layout, motion, colour and fluid type SYSTEM are unchanged. */\n\n`;

for (const w of WANT) {
  const url = pick(w.family, w.weight);
  if (!url) {
    console.log('MISSING', w.family, w.weight);
    continue;
  }
  const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 Chrome/124.0' } });
  fs.writeFileSync(path.join(OUT, w.file), Buffer.from(await res.arrayBuffer()));
  rules += `@font-face {
  font-family: '${w.alias}';
  src: url('/assets/demo/fonts/${w.file}') format('woff2');
  font-weight: ${w.weight};
  font-style: normal;
  font-display: swap;
}\n`;
  // also expose under its own name for the placeholder wordmark <text>
  rules += `@font-face {
  font-family: '${w.family}';
  src: url('/assets/demo/fonts/${w.file}') format('woff2');
  font-weight: ${w.weight};
  font-style: normal;
  font-display: swap;
}\n\n`;
}

fs.writeFileSync('src/styles/demo-fonts.css', rules);
console.log('wrote src/styles/demo-fonts.css and', fs.readdirSync(OUT).length, 'woff2 files');
